        resolve(project, [
          package(
            'studio_paint',
            manifest: {
              'commands': [
                {'name': 'paint'},
              ],
            },
          ),
        ]);
        expect(await runJust(['paint'], context: context()), 1);
        File('${tmp.path}/config/plugins.json')
          ..createSync(recursive: true)
          ..writeAsStringSync('{"allowed": ["studio_paint"]}');
