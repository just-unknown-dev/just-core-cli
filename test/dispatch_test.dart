    );

    test("a pub workspace member trusts the workspace's own store", () async {
      // The workspace's root resolves, and holds the one pubspec.lock; the
      // store is a path dependency, and another member is a plugin too.
      final ws = Directory('${tmp.path}/ws')..createSync();
      File('${ws.path}/pubspec.yaml').writeAsStringSync(
        'name: ws\nworkspace:\n  - game\n  - just_ui_editor\n',
      );
      final member = Directory('${ws.path}/game')..createSync();
      File(
        '${member.path}/pubspec.yaml',
      ).writeAsStringSync('name: game\nresolution: workspace\n');
      File('${member.path}/.dart_tool/pub/workspace_ref.json')
        ..createSync(recursive: true)
        ..writeAsStringSync(jsonEncode({'workspaceRoot': '../../..'}));
      final tools = Directory('${ws.path}/just_ui_editor')..createSync();
      File(
        '${tools.path}/pubspec.yaml',
      ).writeAsStringSync('name: just_ui_editor\nresolution: workspace\n');
      File('${tools.path}/just_plugin.json').writeAsStringSync(
        jsonEncode({
          'commands': [
            {'name': 'ui', 'summary': 'Screens.'},
          ],
        }),
      );
      resolve(ws, [package('just_asset_store', manifest: store), tools]);
      lock(ws, {'just_asset_store': 'path'});

      final found = PluginFinder.inProject(JustProject(member.path));
      expect(
        {for (final p in found) p.package: PluginTrust.isOfficial(p)},
        {'just_asset_store': true, 'just_ui_editor': true},
      );
      final code = await runJust([
        'store',
        'list',
        '--yes',
      ], context: context(cwd: member.path));
      expect(code, 0, reason: '$err');
      expect(launcher.runs.single.arguments.take(2), [
        'run',
        'just_asset_store:just_plugin',
      ]);
    });

    test('a globally activated plugin, once allowed, runs with dart pub '
        'global run', () async {
      final pkg = package(
        'my_tools',
        manifest: {
          'commands': [
            {'name': 'tools', 'summary': 'Tools.'},
          ],
        },
      );
      final global = Directory('${tmp.path}/pub_cache/global_packages/my_tools')
        ..createSync(recursive: true);
      resolve(global, [pkg]);
      lock(global, {'my_tools': 'hosted'});
      // Not allowed yet: --yes doesn't allow it.
      expect(await runJust(['tools', 'x', '--yes'], context: context()), 1);
      expect(launcher.runs, isEmpty);
      expect('$err', contains('plugins.json'));
      // Asked in a terminal, and remembered for the user.
      expect(
        await runJust(['tools', 'x'], context: context(interactive: true)),
        0,
      );
      expect(launcher.runs.single.arguments, [
        'pub',
        'global',
        'run',
        'my_tools:just_plugin',
        'tools',
        'x',
      ]);
      final saved = File('${tmp.path}/config/plugins.json').readAsStringSync();
      expect(jsonDecode(saved), {
        'allowed': ['my_tools'],
      });
      expect(await runJust(['tools', 'y'], context: context()), 0);
    });

    test('a plugin activated from a folder (--source path) is found', () async {
      final pkg = package(
        'my_tools',
        manifest: {
          'commands': [
            {'name': 'tools', 'summary': 'Tools.'},
          ],
        },
      );
      final global = Directory('${tmp.path}/pub_cache/global_packages/my_tools')
        ..createSync(recursive: true);
      // What `dart pub global activate --source path` leaves: a lockfile
      // naming the folder, and no package_config.
      lock(global, {'my_tools': 'path'});
      await runJust(['--help'], context: context());
      expect('$out', contains('tools     Tools. [my_tools]'));
