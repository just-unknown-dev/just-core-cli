// How `just` finds and runs plugins, guards them, and hands a run over to
// the version a project pins — with a launcher that records instead of
// starting processes.

@TestOn('vm')
library;

import 'dart:convert';
import 'dart:io';

import 'package:just_core_cli/just_core_cli.dart';
import 'package:just_core_cli/project.dart';
import 'package:test/test.dart';

final class _Run {
  _Run(
    this.executable,
    this.arguments,
    this.workingDirectory,
    this.env,
    this.toStderr, {
    this.captured = false,
  });
  final String executable;
  final List<String> arguments;
  final String? workingDirectory;
  final Map<String, String> env;
  final bool toStderr;

  /// Whether its stdout was read (for its `--json` document).
  final bool captured;
}

final class _FakeLauncher implements Launcher {
  final List<_Run> runs = [];
  int exitCode = 0;

  /// Thrown instead of running, when set.
  Object? throws;

  /// Called for each run, after it is recorded.
  void Function(_Run run)? onRun;

  /// What a run whose stdout is read prints there: `dart run`'s own line,
  /// then a plugin's document naming its arguments.
  String Function(List<String> arguments) printed = (args) =>
      'Building package executable...\n'
      '${const JsonEncoder.withIndent('  ').convert({
        'ok': true,
        'result': {'args': args.skip(2).join(' ')},
        'warnings': ['from the plugin'],
      })}\n';

  @override
  Future<int> run(
    String executable,
    List<String> arguments, {
    String? workingDirectory,
    Map<String, String> environment = const {},
    bool toStderr = false,
    StringSink? stdout,
  }) async {
    final run = _Run(
      executable,
      arguments,
      workingDirectory,
      environment,
      toStderr,
      captured: stdout != null,
    );
    runs.add(run);
    if (throws case final error?) throw error;
    onRun?.call(run);
    stdout?.write(printed(arguments));
    return exitCode;
  }
}

void main() {
  late Directory tmp;
  late Directory project;
  late _FakeLauncher launcher;
  late StringBuffer out, err;

  /// A package [name] at [version] in tmp, adding [manifest] when given.
  Directory package(String name, {String version = '1.0.0', Object? manifest}) {
    final dir = Directory('${tmp.path}/pkgs/$name')
      ..createSync(recursive: true);
    File(
      '${dir.path}/pubspec.yaml',
    ).writeAsStringSync('name: $name\nversion: $version\n');
    if (manifest != null) {
      File(
        '${dir.path}/just_plugin.json',
      ).writeAsStringSync(jsonEncode(manifest));
    }
    return dir;
  }

  /// [dir]'s package_config, resolving [packages].
  void resolve(Directory dir, List<Directory> packages) {
    final file = File('${dir.path}/.dart_tool/package_config.json')
      ..createSync(recursive: true);
    file.writeAsStringSync(
      jsonEncode({
        'configVersion': 2,
        'packages': [
          for (final p in packages)
            {
              'name': p.uri.pathSegments.where((s) => s.isNotEmpty).last,
              'rootUri': p.absolute.uri.toString(),
              'packageUri': 'lib/',
            },
        ],
      }),
    );
  }

  /// [dir]'s pubspec.lock, naming each package's source: `path` (the
  /// package in tmp/pkgs), `hosted` (pub.dev), `hosted:<server url>`, or a
  /// git URL.
  void lock(Directory dir, Map<String, String> sources) {
    final b = StringBuffer('# Generated by pub\npackages:\n');
    sources.forEach((name, source) {
      b.writeln('  $name:');
      b.writeln('    dependency: "direct dev"');
      b.writeln('    description:');
      if (source == 'path') {
        final path = '${tmp.path}/pkgs/$name'.replaceAll(r'\', r'\\');
        b
          ..writeln('      path: "$path"')
          ..writeln('      relative: false')
          ..writeln('    source: path');
      } else if (source.startsWith('hosted')) {
        final server = source == 'hosted'
            ? 'https://pub.dev'
            : source.substring('hosted:'.length);
        b
          ..writeln('      name: $name')
          ..writeln('      url: "$server"')
          ..writeln('    source: hosted');
      } else {
        b
          ..writeln('      path: "."')
          ..writeln('      ref: v1.0.0')
          ..writeln('      url: "$source"')
          ..writeln('    source: git');
      }
      b.writeln('    version: "1.0.0"');
    });
    b.writeln('sdks:\n  dart: ">=3.11.0 <4.0.0"');
    File('${dir.path}/pubspec.lock').writeAsStringSync('$b');
  }

  JustContext context({
    bool interactive = false,
    Map<String, String> env = const {},
    String invokedAs = 'just',
    String? cwd,
  }) => JustContext(
    workingDirectory: cwd ?? project.path,
    out: out,
    err: err,
    interactive: interactive,
    readLine: () => 'y',
    environment: {
      'PUB_CACHE': '${tmp.path}/pub_cache',
      'JUST_CORE_CLI_CONFIG_DIR': '${tmp.path}/config',
      ...env,
    },
    invokedAs: invokedAs,
    launcher: launcher,
  );

  const store = {
    'schema': 1,
    'commands': [
      {'name': 'store', 'summary': 'Store things.'},
    ],
    'shortcuts': {'add': 'store install'},
  };

  /// The ecosystem's store, from a local checkout.
  void officialStore(Directory dir) {
    resolve(dir, [package('just_asset_store', manifest: store)]);
    lock(dir, {'just_asset_store': 'path'});
  }

  const game = {
    'schema': 1,
    'commands': [
      {'name': 'game', 'summary': 'Games.'},
    ],
    'hooks': {
      'create': 'game init',
      'check': 'game check',
      'doctor': 'game doctor',
      'migrate': 'game migrate',
    },
  };

  /// The ecosystem's game plugin and its store (with a check hook), from
  /// local checkouts, and someone else's plugin with a check hook too.
  void officialGame(Directory dir) {
    resolve(dir, [
      package(
        'just_asset_store',
        manifest: {
          ...store,
          'hooks': {'check': 'store generate --check'},
        },
      ),
      package('just_game_engine_cli', manifest: game),
      package(
        'studio_paint',
        manifest: {
          'commands': [
            {'name': 'paint'},
          ],
          'hooks': {'check': 'paint check'},
        },
      ),
    ]);
    lock(dir, {
      'just_asset_store': 'path',
      'just_game_engine_cli': 'path',
      'studio_paint': 'hosted',
    });
  }

  setUp(() {
    tmp = Directory.systemTemp.createTempSync('just_dispatch_');
    project = Directory('${tmp.path}/game')..createSync();
    File('${project.path}/pubspec.yaml').writeAsStringSync('name: game\n');
    launcher = _FakeLauncher();
    out = StringBuffer();
    err = StringBuffer();
  });

