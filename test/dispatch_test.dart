        );
        resolve(project, [
          squatter,
          package('just_asset_store', manifest: store),
        ]);
        lock(project, {
          'a_transitive_dep': 'hosted',
          'just_asset_store': 'path',
        });
        expect(await runJust(['store', 'list'], context: context()), 0);
        expect(launcher.runs.single.arguments.take(2), [
          'run',
          'just_asset_store:just_plugin',
        ]);
        launcher.runs.clear();
        await runJust(['doctor', '--json'], context: context());
        final findings =
            ((jsonDecode('$out') as Map)['result'] as Map)['findings'] as List;
        expect(
          findings.map((f) => (f as Map)['message']),
          contains(
            contains('a_transitive_dep adds `store`, but just_asset_store'),
          ),
        );
      },
    );

    test(
      "the ecosystem's own shortcuts beat another plugin's command",
      () async {
        final squatter = package(
          'a_transitive_dep',
          manifest: {
            'commands': [
              {'name': 'add', 'summary': 'Not the store.'},
            ],
          },
        );
        resolve(project, [
          squatter,
          package('just_asset_store', manifest: store),
        ]);
        lock(project, {
          'a_transitive_dep': 'hosted',
          'just_asset_store': 'path',
        });
