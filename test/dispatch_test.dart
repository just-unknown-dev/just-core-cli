    });

    test('allowed once, it is remembered in just.json', () async {
      resolve(project, [package('studio_paint', manifest: other)]);
      expect(await runJust(['paint'], context: context(interactive: true)), 0);
      expect(launcher.runs, hasLength(1));
      final file = JustProject(project.path).readProjectFile();
      expect(file.allowedPlugins, ['studio_paint']);
      // No question the second time.
      expect(await runJust(['paint'], context: context()), 0);
      expect(launcher.runs, hasLength(2));
    });

    test(
      "an ecosystem name is trusted only from the ecosystem's sources",
      () async {
        resolve(project, [package('just_asset_store', manifest: store)]);
        lock(project, {'just_asset_store': 'hosted:https://pub.example.com'});
        expect(await runJust(['store', 'list'], context: context()), 1);
        expect(launcher.runs, isEmpty);
        expect('$err', contains('not from a local checkout'));

        // pub.dev counts for the names the ecosystem published there: the
        // store's is one since 0.1.1…
        lock(project, {'just_asset_store': 'hosted'});
        expect(await runJust(['store', 'list'], context: context()), 0);
        expect(launcher.runs, hasLength(1));

        // …and only for those: another of its names, not published there
        // yet, could be anyone's.
        resolve(project, [package('just_sprite_editor', manifest: store)]);
        lock(project, {'just_sprite_editor': 'hosted'});
        expect(await runJust(['store', 'list'], context: context()), 1);
        expect(launcher.runs, hasLength(1));

        resolve(project, [package('just_asset_store', manifest: store)]);
        lock(project, {
          'just_asset_store':
              'https://github.com/just-unknown-dev/just-asset-store',
        });
        expect(await runJust(['store', 'list'], context: context()), 0);
      },
    );

    test('which sources count as the ecosystem', () {
      Plugin plugin(String name, PluginSource source) => Plugin(
        package: name,
        root: '.',
        manifest: const PluginManifest(),
        scope: PluginScope.project,
        source: source,
      );
      const path = PluginSource('path', path: '/x');
      const hosted = PluginSource('hosted', url: 'https://pub.dev');
      const mirror = PluginSource('hosted', url: 'https://pub.example.com');
      expect(
        PluginTrust.trusted(plugin('just_asset_store', path), const []),
        isTrue,
      );
      expect(
        PluginTrust.trusted(plugin('just_sprite_editor', hosted), const []),
        isFalse,
        reason: 'not one the ecosystem has published on pub.dev',
      );
      expect(
        PluginTrust.trusted(plugin('just_asset_store', hosted), const []),
        isTrue,
        reason: 'published on pub.dev after 0.1.1',
      );
      expect(PluginTrust.onPubDev, everyElement(isIn(PluginTrust.official)));
      expect(
        PluginTrust.trusted(plugin('just_asset_store', mirror), const []),
        isFalse,
      );
      expect(
        PluginTrust.trusted(plugin('just_game_engine_cli', hosted), const []),
        isTrue,
      );
      for (final url in [
        'https://pub.dev',
        'https://pub.dev/',
        'https://PUB.dev',
      ]) {
        expect(PluginTrust.isPubDev(url), isTrue, reason: url);
      }
      for (final url in [
        'http://pub.dev',
        'https://pub.dev.evil.example',
        'https://pub.dev:8443',
        'https://pub.dev/mirror',
        'https://pub.dartlang.org',
      ]) {
        expect(PluginTrust.isPubDev(url), isFalse, reason: url);
      }
      expect(
        PluginTrust.trusted(plugin('just_asset_store_evil', path), const []),
        isFalse,
      );
      expect(PluginTrust.trusted(plugin('x', hosted), const ['x']), isTrue);
      for (final url in [
        'https://github.com/just-unknown-dev/just-asset-store',
        'https://github.com/just-unknown-dev/just-asset-store.git',
        'git@github.com:just-unknown-dev/just-asset-store.git',
      ]) {
        expect(PluginTrust.isEcosystemRepository(url), isTrue, reason: url);
      }
      for (final url in [
        'https://github.com/someone/just-asset-store',
        'https://github.com.evil.example/just-unknown-dev/x',
        'https://evil.example/github.com/just-unknown-dev/x',
        'https://github.com/just-unknown-dev.evil/x',
        'http://github.com/just-unknown-dev/x',
      ]) {
        expect(PluginTrust.isEcosystemRepository(url), isFalse, reason: url);
      }
    });
  });

  group('pinning', () {
