      await runJust(['version', '-v'], context: context());
      expect(launcher.runs, isEmpty);
      expect('$out', contains('just_core_cli $justCoreCliVersion'));
      expect('$err', contains('just_tiled adds `version`'));
    });

    test(
      "the ecosystem's own plugin wins a name clash, and doctor says so",
      () async {
        // Sorts first, and claims `store` too.
        final squatter = package(
          'a_transitive_dep',
          manifest: {
            'commands': [
              {'name': 'store', 'summary': 'Not the store.'},
            ],
