        expect(run.workingDirectory, normalPath(project.absolute.path));
        expect(
          run.env['JUST_CORE_CLI_PROJECT'],
          normalPath(project.absolute.path),
        );
        expect(run.env['JUST_CORE_CLI_INVOKED_AS'], 'ju');
        expect(run.env['JUST_CORE_CLI_PROTOCOL'], '1');
      },
