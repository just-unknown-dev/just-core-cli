        ['--project', project.path, 'upgrade', '--help'],
        ['--project=${project.path}', 'upgrade', '--help'],
        ['upgrade', '--help', '--project', project.path],
      ]) {
        final ctx = JustContext(
          workingDirectory: tmp.path,
          out: out,
          err: err,
          interactive: false,
          environment: {'PUB_CACHE': '${tmp.path}/none'},
          launcher: launcher,
        );
        expect(await runJust(args, context: ctx), 0, reason: '$args');
        expect(launcher.runs, isEmpty, reason: '$args');
      }
    });

    test('a fresh clone gets its packages first', () async {
      File('${project.path}/pubspec.yaml').writeAsStringSync(
        'name: game\ndev_dependencies:\n  just_core_cli: ^0.1.0\n',
      );
      await runJust(['version'], context: context());
      expect(launcher.runs.first.arguments, ['pub', 'get']);
      expect(launcher.runs.first.toStderr, isFalse);
      expect('$err', contains('pins its own just'));
    });

    test("with --json, the fresh clone's pub get prints to stderr", () async {
      File('${project.path}/pubspec.yaml').writeAsStringSync(
        'name: game\ndev_dependencies:\n  just_core_cli: ^0.1.0\n',
      );
      launcher.onRun = (run) {
        if (run.arguments.contains('get')) {
          resolve(project, [package('just_core_cli', version: '0.0.9')]);
        }
      };
      await runJust(['--json', 'version'], context: context());
      expect(launcher.runs.first.arguments, ['pub', 'get']);
      expect(launcher.runs.first.toStderr, isTrue);
      expect(launcher.runs.last.arguments, [
        'run',
        'just_core_cli:just',
        '--json',
        'version',
      ]);
    });

    test('a hand-over that cannot start is a message, not a crash', () async {
      pin('9.9.9');
      launcher.throws = const ProcessException('dart', [
        'run',
      ], 'The system cannot find the file specified.');
      final code = await runJust(['--json', 'version'], context: context());
      expect(code, 1);
      expect('$err', contains('Could not start dart'));
      expect('$err', isNot(contains('#0')));
      final doc = jsonDecode('$out') as Map;
      expect(doc['ok'], isFalse);
      expect(doc['error'], contains('Could not start dart'));

      launcher.throws = const CommandFailure('Refused.');
      out.clear();
      expect(await runJust(['version'], context: context()), 1);
      expect('$err', contains('Refused.'));
    });
  });

  group('--version', () {
    test('before the command, it is the version; after, not', () async {
      expect(await runJust(['--version'], context: context()), 0);
      expect('$out', 'just_core_cli $justCoreCliVersion\n');
      out.clear();
      officialGame(project);
      expect(
        await runJust([
          'game',
          'scene',
          'list',
          '--version',
        ], context: context()),
        0,
      );
      expect('$out', isEmpty, reason: 'the plugin answers');
      expect(launcher.runs.single.arguments, [
        'run',
        'just_game_engine_cli:just_plugin',
        'game',
        'scene',
        'list',
        '--version',
      ]);
    });

    test('with --json, the version is in the result', () async {
      expect(await runJust(['--json', '--version'], context: context()), 0);
      final doc = jsonDecode('$out') as Map;
      expect(doc['ok'], isTrue);
      expect((doc['result'] as Map)['version'], justCoreCliVersion);
    });

    test("a plugin's own --version reaches it", () async {
      officialStore(project);
      await runJust(['store', 'list', '--version'], context: context());
      expect(launcher.runs.single.arguments.last, '--version');
    });
  });

  group('check', () {
    test("runs the ecosystem's plugins' check hooks, passing on --json and "
        '--verbose', () async {
      officialGame(project);
      expect(
        await runJust(['check', '--json', '-v'], context: context()),
        0,
        reason: '$err',
      );
      expect(
        [for (final r in launcher.runs) r.arguments.skip(2).join(' ')],
        [
          'store generate --check --json --verbose',
          'game check --json --verbose',
        ],
        reason: "studio_paint isn't trusted, and nobody was there to ask",
      );
      expect('$err', contains("Skipped studio_paint's `check` hook"));
      expect('$err', contains('just.json'));
      // Each plugin's own document is read, and kept in the result.
      expect(launcher.runs.every((r) => r.captured), isTrue);
      expect('$err', contains('Building package executable'));
      final result = (jsonDecode('$out') as Map)['result'] as Map;
      expect(result.keys, ['just_asset_store', 'just_game_engine_cli']);
      expect(result['just_game_engine_cli'], {
        'hook': 'game check',
        'ok': true,
        'exitCode': 0,
        'result': {'args': 'game check --json --verbose'},
        'warnings': ['from the plugin'],
      });

      launcher.runs.clear();
      launcher.exitCode = 1;
      out.clear();
      expect(await runJust(['check'], context: context()), 1);
      expect(launcher.runs, hasLength(2), reason: 'every check runs');
      expect(launcher.runs.any((r) => r.captured), isFalse);
    });

    test('a plugin allowed when asked has its check run too', () async {
      officialGame(project);
      expect(
        await runJust(['check'], context: context(interactive: true)),
        0,
        reason: '$err',
      );
      expect(launcher.runs.last.arguments.skip(2), ['paint', 'check']);
      expect(JustProject(project.path).readProjectFile().allowedPlugins, [
        'studio_paint',
      ]);
    });

    test("behind a package mirror, the ecosystem's names are asked about, "
        'never skipped without a word', () async {
      resolve(project, [package('just_game_engine_cli', manifest: game)]);
      lock(project, {'just_game_engine_cli': 'hosted:https://pub.example.com'});
      expect(await runJust(['check'], context: context()), 1);
      expect(launcher.runs, isEmpty);
      expect('$err', contains("Skipped just_game_engine_cli's `check` hook"));
      expect('$err', contains('Nothing was checked'));
      // Allowed in just.json, as any plugin can be.
      JustProject(project.path).writeProjectFile(
        const JustProjectFile(allowedPlugins: ['just_game_engine_cli']),
      );
      expect(await runJust(['check'], context: context()), 0);
      expect(launcher.runs.single.arguments.skip(2), ['game', 'check']);
    });

    test('never passes without checking', () async {
      expect(await runJust(['check'], context: context()), 1);
      expect('$err', contains('have not been fetched'));
      resolve(project, [package('just_tiled')]);
      expect(await runJust(['check'], context: context()), 1);
      expect('$err', contains('no installed plugin'));
    });

    test(
      "takes no names: a plugin's own checks are under its command",
      () async {
        expect(
          await runJust(['check', 'release-build'], context: context()),
          ExitCodes.usage,
        );
        expect('$err', isNot(contains('Unexpected error')));
      },
    );
  });

  test("help on a plugin's command is the plugin's own help", () async {
    officialGame(project);
    expect(
      await runJust(['help', 'game', 'run'], context: context()),
      0,
      reason: '$err',
    );
    expect(launcher.runs.single.arguments, [
      'run',
      'just_game_engine_cli:just_plugin',
      'game',
      'run',
      '--help',
    ]);
    launcher.runs.clear();
    expect(await runJust(['help', 'doctor'], context: context()), 0);
    expect(launcher.runs, isEmpty, reason: 'a built-in command has its own');
    expect('$out', contains('just doctor'));
  });

  test('--project works before or after the command', () async {
    final elsewhere = Directory('${tmp.path}/other')..createSync();
    File('${elsewhere.path}/pubspec.yaml').writeAsStringSync('name: other\n');
    officialStore(elsewhere);
    final ctx = JustContext(
      workingDirectory: tmp.path,
      out: out,
      err: err,
      interactive: false,
      environment: {'PUB_CACHE': '${tmp.path}/none'},
      launcher: launcher,
    );
    await runJust(['store', 'list', '--project', elsewhere.path], context: ctx);
    expect(
      launcher.runs.single.workingDirectory,
      normalPath(elsewhere.absolute.path),
    );
  });

  test('a --project folder without a pubspec is no project', () async {
    final typo = Directory('${tmp.path}/gmae')..createSync();
    final ctx = context();
    expect(
      await runJust(['dev', 'unlink', '--project', typo.path], context: ctx),
      1,
    );
    expect('$err', contains('No pubspec.yaml in ${typo.path} (--project)'));
    expect(Directory('${typo.path}/.dart_tool').existsSync(), isFalse);
  });

  test('a project named after the context was read is the one used', () {
    final ctx = context();
    expect(ctx.project!.root, normalPath(project.absolute.path));
    final elsewhere = Directory('${tmp.path}/other')..createSync();
    File('${elsewhere.path}/pubspec.yaml').writeAsStringSync('name: other\n');
    ctx.projectOverride = elsewhere.path;
    expect(ctx.project!.root, normalPath(elsewhere.absolute.path));
  });
