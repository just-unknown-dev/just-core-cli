  });

  group('trust', () {
    final other = {
      'commands': [
        {'name': 'paint', 'summary': 'Paints.'},
      ],
    };

    test('a plugin from outside the ecosystem is not run unasked', () async {
      resolve(project, [package('studio_paint', manifest: other)]);
      expect(await runJust(['paint'], context: context()), 1);
      expect(launcher.runs, isEmpty);
      expect('$err', contains('studio_paint 1.0.0 adds `just paint`'));
      expect('$err', contains('just.json'));
    });

    test('--yes never allows one, nor saves it', () async {
      resolve(project, [package('studio_paint', manifest: other)]);
      expect(
        await runJust(['paint', '--yes'], context: context(interactive: true)),
