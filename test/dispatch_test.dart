      expect(found.single.source.kind, 'path');
    });

    test('a broken manifest is left out, and said with --verbose', () async {
      final bad = package('just_ui_editor');
      File('${bad.path}/just_plugin.json').writeAsStringSync('{"commands": 3}');
      resolve(project, [bad]);
      expect(await runJust(['nope', '-v'], context: context()), 2);
      expect('$err', contains('just_ui_editor'));
    });

    test('a manifest or a pubspec that is not UTF-8 is a message, never a '
        'stack trace', () async {
      final bad = package('just_ui_editor');
      File(
        '${bad.path}/just_plugin.json',
      ).writeAsBytesSync([0x7B, 0xFF, 0xFE, 0x7D]);
      resolve(project, [bad]);
      expect(await runJust(['version', '-v'], context: context()), 0);
      expect('$err', contains('just_ui_editor: just_plugin.json could not'));
      out.clear();

      File('${project.path}/pubspec.yaml').writeAsBytesSync([
        ...utf8.encode('name: game\ndev_dependencies:\n  just_core_cli: ^'),
        0xFF,
        0xFE,
      ]);
      expect(await runJust(['--json', 'doctor'], context: context()), 1);
      expect('$err', isNot(contains('#0')));
      expect((jsonDecode('$out') as Map)['ok'], isFalse);
    });

    test(
      'flags given before the name reach the plugin before its --',
      () async {
        officialStore(project);
        await runJust([
          '--json',
          '--yes',
          'store',
